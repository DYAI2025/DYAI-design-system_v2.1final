/* ============================================================
   DESTILL — pure logic (no DOM). Loaded as a classic script in
   the browser (window.DestillLogic) and require()-able in Node
   for unit tests. Everything here is deterministic and testable.
   ============================================================ */
(function (root, factory) {
  if (typeof module === "object" && module.exports) {
    module.exports = factory();
  } else {
    root.DestillLogic = factory();
  }
})(typeof self !== "undefined" ? self : this, function () {
  "use strict";

  /* ---- time formatting ---- */
  function fmtTime(sec) {
    sec = Math.max(0, Math.round(sec));
    var m = Math.floor(sec / 60);
    var s = sec % 60;
    return m + ":" + (s < 10 ? "0" : "") + s;
  }
  function fmtTimePadded(sec) {
    sec = Math.max(0, Math.round(sec));
    var m = Math.floor(sec / 60);
    var s = sec % 60;
    return (m < 10 ? "0" + m : "" + m) + ":" + (s < 10 ? "0" : "") + s;
  }

  /* ---- decisions & outcome math ---- */
  var DECISIONS = ["keep", "change", "drop"];

  function computeOutcome(segments) {
    var out = { keep: 0, change: 0, drop: 0, seconds: 0, removed: 0, total: 0 };
    segments.forEach(function (s) {
      var d = s.decision || "keep";
      var len = s.end - s.start;
      out.total += len;
      out[d] += 1;
      if (d === "drop") { out.removed += len; }
      else { out.seconds += len; } // "change" keeps runtime, flags a rework note
    });
    return out;
  }

  /* ---- state machine ---- */
  var STATES = ["welcome", "source", "processing", "cancelled",
    "blocked-analyze", "understanding", "refine", "result", "blocked-render"];

  var TRANSITIONS = {
    welcome:           ["source"],
    source:            ["processing", "blocked-analyze", "welcome"],
    processing:        ["understanding", "cancelled"],
    cancelled:         ["processing", "source"],
    "blocked-analyze": ["source", "processing"],
    understanding:     ["refine", "source"],
    refine:            ["result", "blocked-render", "understanding", "source"],
    result:            ["refine", "source"],
    "blocked-render":  ["refine", "result", "source"]
  };

  function canGo(from, to) {
    return (TRANSITIONS[from] || []).indexOf(to) !== -1;
  }

  /* Step rail mapping: which journey step a state sits on. */
  function stepOf(state) {
    switch (state) {
      case "welcome":
      case "source":
      case "blocked-analyze":   return 0;
      case "processing":
      case "cancelled":
      case "understanding":     return 1;
      case "refine":            return 2;
      case "result":
      case "blocked-render":    return 3;
      default:                  return 0;
    }
  }

  /* ---- CapCut EditPilot prompt (English, copyable) ---- */
  function buildPrompt(opts) {
    var o = opts || {};
    var segs = o.segments || [];
    var lines = [];
    lines.push("CapCut EditPilot prompt — generated by Destill (design proposal)");
    lines.push("Source: " + (o.sourceName || "untitled clip"));
    if (o.intent) { lines.push("Intent: " + o.intent); }
    lines.push("Target runtime: about " + fmtTime(o.targetSeconds || 90) + ".");
    lines.push("");
    segs.forEach(function (s) {
      var d = s.decision || "keep";
      if (d === "drop") {
        lines.push("- Remove " + fmtTimePadded(s.start) + "–" + fmtTimePadded(s.end) + " (" + s.title + ").");
      } else if (d === "change") {
        lines.push("- Rework " + fmtTimePadded(s.start) + "–" + fmtTimePadded(s.end) + " (" + s.title + "): tighten pacing, keep the point.");
      }
    });
    lines.push("- Keep the remaining segments in source order; preserve ambient audio under speech.");
    lines.push("- No added music, captions or effects unless the intent above asks for them.");
    return lines.join("\n");
  }

  /* ---- synthetic demonstration dataset ----
     Labelled SYNTHETIC everywhere it appears. No model ran.     */
  var DEMO_SOURCE = {
    synthetic: true,
    name: "destill_synthetic_source.mp4",
    seconds: 252,
    width: 1920,
    height: 1080,
    note: "A notional studio take used only to demonstrate the interface."
  };

  function demoSegments() {
    return [
      { id: "s1", start: 0,   end: 14,  role: "hook",     title: "Cold open — the claim up front",
        note: "One sentence states what the video argues. Strong opening.", decision: "keep" },
      { id: "s2", start: 14,  end: 52,  role: "claim",    title: "Core claim — local-first review",
        note: "The central claim, spoken to camera without cuts.", decision: "keep" },
      { id: "s3", start: 52,  end: 96,  role: "evidence", title: "Screen capture — timeline review",
        note: "Shows the review workflow the claim describes.", decision: "keep" },
      { id: "s4", start: 96,  end: 132, role: "aside",    title: "Tangent — microphone setup",
        note: "Leaves the subject for 36 seconds; returns no new point.", decision: "drop" },
      { id: "s5", start: 132, end: 178, role: "claim",    title: "Second claim — evidence-linked notes",
        note: "Extends the core claim and references the capture.", decision: "keep" },
      { id: "s6", start: 178, end: 214, role: "evidence", title: "Walkthrough — accepting a cut",
        note: "Longer than the point needs; pacing could tighten.", decision: "change" },
      { id: "s7", start: 214, end: 252, role: "outro",    title: "Outro — repeats the claim",
        note: "Restates the opening sentence verbatim; redundant.", decision: "drop" }
    ];
  }

  function demoEvidence() {
    return [
      { t: 3,   seg: "s1", text: "The claim is stated in a single sentence, before any framing." },
      { t: 21,  seg: "s2", text: "Claim spoken to camera; no supporting visual for 38 seconds." },
      { t: 58,  seg: "s3", text: "Screen capture matches what the claim describes." },
      { t: 101, seg: "s4", text: "Subject leaves frame; audio becomes setup chatter." },
      { t: 139, seg: "s5", text: "Second claim explicitly references the first." },
      { t: 184, seg: "s6", text: "The same gesture is shown twice; one pass would suffice." },
      { t: 219, seg: "s7", text: "Closing sentence repeats the opening verbatim." }
    ];
  }

  /* ---- processing stages (synthetic timing only) ---- */
  function demoStages() {
    return [
      { id: "ingest",   label: "Ingest — read local metadata" },
      { id: "listen",   label: "Listen — sketch what is said" },
      { id: "structure",label: "Structure — group claim, evidence, aside" },
      { id: "evidence", label: "Evidence — link notes to source time" }
    ];
  }

  return {
    fmtTime: fmtTime,
    fmtTimePadded: fmtTimePadded,
    DECISIONS: DECISIONS,
    computeOutcome: computeOutcome,
    STATES: STATES,
    TRANSITIONS: TRANSITIONS,
    canGo: canGo,
    stepOf: stepOf,
    buildPrompt: buildPrompt,
    DEMO_SOURCE: DEMO_SOURCE,
    demoSegments: demoSegments,
    demoEvidence: demoEvidence,
    demoStages: demoStages
  };
});
